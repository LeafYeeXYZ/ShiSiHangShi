"""Generate a core font and lazy fallback chunks without dropping supported characters."""

import hashlib
import json
import re
from copy import deepcopy
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data/fonts/NotoSerifSC-Regular.ttf"
OUTPUT = ROOT / "public/fonts"
CSS = ROOT / "src/font-face.css"
CHUNK_SIZE = 256


def unicode_ranges(points):
    ranges = []
    for point in sorted(points):
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ", ".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in ranges
    )


def main():
    font = TTFont(SOURCE, recalcTimestamp=False)
    supported = set(font.getBestCmap())
    # Include control characters and non-breaking spaces used by browser layout.
    used = set(range(256)) | set(range(0x2000, 0x2070))
    text_files = [ROOT / "index.html", *sorted((ROOT / "src").rglob("*.tsx")),
                  *sorted((ROOT / "src").rglob("*.ts")),
                  ROOT / "data/original.json", ROOT / "data/migrate.json"]
    for path in text_files:
        used.update(map(ord, path.read_text()))
    core = supported & used
    remainder = sorted(supported - core)
    groups = [("core", core)] + [
        (f"extra-{index // CHUNK_SIZE:03}", remainder[index:index + CHUNK_SIZE])
        for index in range(0, len(remainder), CHUNK_SIZE)
    ]
    OUTPUT.mkdir(exist_ok=True)
    rules = ["/* Generated by scripts/subset_font.py. */"]
    generated = set()
    stats = []
    for label, points in groups:
        part = deepcopy(font)
        options = subset.Options()
        options.flavor = "woff2"
        options.recalc_timestamp = False
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=points)
        subsetter.subset(part)
        part.flavor = "woff2"
        temporary = OUTPUT / f"NotoSerifSC-{label}.woff2"
        part.save(temporary)
        # Check every requested character survived subsetting.
        with TTFont(temporary) as result:
            assert set(points).issubset(result.getBestCmap())
        digest = hashlib.sha256(temporary.read_bytes()).hexdigest()[:12]
        target = OUTPUT / f"NotoSerifSC-{label}-{digest}.woff2"
        temporary.replace(target)
        generated.add(target)
        stats.append({"group": label, "characters": len(points), "bytes": target.stat().st_size})
        rules.append(
            "@font-face {\n"
            "  font-family: 'Noto Serif SC';\n"
            f"  src: url('/fonts/{target.name}') format('woff2');\n"
            "  font-style: normal;\n"
            "  font-weight: 400;\n"
            "  font-display: swap;\n"
            f"  unicode-range: {unicode_ranges(points)};\n"
            "}"
        )
    assert len(core) + len(remainder) == len(supported)
    CSS.write_text("\n\n".join(rules) + "\n")
    core_file = next(path.name for path in generated if "-core-" in path.name)
    html_path = ROOT / "index.html"
    html = re.sub(r'    <link[^>]*data-sonnet-font[^>]*>\n', '', html_path.read_text())
    preload = (f'    <link rel="preload" href="/fonts/{core_file}" as="font" '
               'type="font/woff2" crossorigin data-sonnet-font>\n')
    html_path.write_text(html.replace('    <title>', preload + '    <title>'))
    for path in OUTPUT.glob("NotoSerifSC-*.woff2"):
        if path not in generated:
            path.unlink()
    print(json.dumps({"original_bytes": SOURCE.stat().st_size, "core": stats[0],
                      "fallback_chunks": len(stats) - 1,
                      "total_bytes": sum(item["bytes"] for item in stats)}, indent=2))


if __name__ == "__main__":
    main()
